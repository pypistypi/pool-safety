#pragma once

// ---------------------------------------------------------------------------
//  Общая точка входа в ONNX Runtime.
//
//  Моделей в программе стало две: поиск людей (YOLOv5n) и оценка позы
//  (RTMPose). Библиотека у них одна, весит 13 МБ, и подключать её дважды
//  незачем. Раньше загрузка жила внутри PersonDetector.cpp; вынесена сюда,
//  чтобы вторая модель не заводила себе копию тех же двадцати строк — а
//  вместе с ними и второй способ ошибиться.
//
//  Заголовок ONNX Runtime сюда НЕ подключается: он тянет за собой сотни
//  килобайт объявлений в каждый файл, который его увидит. Наружу торчат
//  только два указателя, объявленных вперёд.
// ---------------------------------------------------------------------------

#include <QString>

struct OrtApi;
struct OrtStatus;

namespace core {

/// Подключить onnxruntime.dll (при первом обращении) и вернуть таблицу
/// функций. nullptr — библиотека недоступна, причина в runtimeError().
const OrtApi *ortApi();

/// Почему библиотека не загрузилась. Пустая строка — всё в порядке.
QString ortRuntimeError();

/// Разобрать код возврата библиотеки и ОСВОБОДИТЬ его.
///
/// Освобождать обязан вызывающий, иначе при каждой ошибке подтекает память.
/// Поэтому через эту обёртку проходят даже те вызовы, чей отказ нас не
/// остановит: забыть про освобождение здесь просто негде.
QString ortTakeStatus(OrtStatus *status);

} // namespace core
