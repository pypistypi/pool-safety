#pragma once

// ---------------------------------------------------------------------------
//  Модель постоянного окружения: что в кадре никогда не шевелится.
//
//  ЧТО ЭТО ТАКОЕ И ЧЕМ ОНО НЕ ЯВЛЯЕТСЯ
//
//  Это НЕ дообучение нейросети. Дообучать распознавание людей на объекте
//  нельзя: для этого нужна разметка «здесь человек, здесь нет», которой взять
//  неоткуда, а самообучение детектора без разметки неизбежно сползает в
//  деградацию — модель начинает пропускать людей, и узнают об этом на
//  настоящем происшествии. Для системы безопасности это недопустимо.
//
//  Это статистика по кадру, накопленная за дни работы. Кадр делится на сетку
//  ячеек, и для каждой копится одно число: насколько она обычно меняется от
//  разбора к разбору. Плитка на дне, стена, дверной проём меняются почти
//  никак. Дорожка, где ходят люди, меняется постоянно.
//
//  ПОЧЕМУ ИЗМЕНЧИВОСТЬ, А НЕ ЦВЕТ. Потому что цвет зависит от света: к вечеру
//  вся картинка темнеет, и модель, запомнившая дневные цвета, объявила бы
//  чужим весь кадр разом. Изменчивость от света почти не зависит: солнце
//  садится медленно и одинаково всюду, а человек проходит быстро и в одном
//  месте.
//
//  КАК ЭТО ИСПОЛЬЗУЕТСЯ — И ЧЕГО ОНА НЕ ДЕЛАЕТ НИКОГДА
//
//  Модель НЕ ПОДАВЛЯЕТ обнаружение людей. Человек может стоять неподвижно час,
//  и в мёртвой зоне кадра он тем более важен, а не менее. Всё, что она даёт, —
//  повод отнестись к слабому отклику модели с большим сомнением там, где за
//  недели наблюдения не менялось ничего. Сильный отклик проходит всегда.
//
//  ЕСЛИ СЦЕНА ИЗМЕНИЛАСЬ, МОДЕЛЬ МОЛЧИТ. Камеру повернули, переставили мебель,
//  сменили ракурс — накопленное перестаёт описывать то, что видно. Модель сама
//  считает долю совпадения и, если она мала, отключается до нового обучения.
//  Опираться на устаревшую карту опаснее, чем не иметь никакой.
// ---------------------------------------------------------------------------

#include <QImage>
#include <QString>
#include <QVector>

namespace core {

class BackgroundModel
{
public:
    /// Сколько ячеек по ширине и высоте.
    ///
    /// Сетка нарочно грубая. Мелкая ячейка ловит дрожание камеры и шум
    /// матрицы, а нам нужны крупные области: «здесь стена», «здесь дорожка».
    static constexpr int kGridWidth = 32;
    static constexpr int kGridHeight = 18;
    static constexpr int kCells = kGridWidth * kGridHeight;

    /// Сколько разборов нужно, чтобы модели можно было верить.
    ///
    /// При разборе 8 раз в секунду это около часа непрерывной работы. Меньше
    /// брать нельзя: за десять минут «постоянным окружением» окажется и
    /// человек, задремавший на лежаке.
    static constexpr int kMinSamples = 30000;

    /// Ниже какой доли совпадения модель считается непригодной.
    static constexpr double kMinAgreement = 0.35;

    BackgroundModel() = default;

    /// Учесть очередной кадр. Вызывается из вычислительного потока.
    void observe(const QImage &frame);

    /// Насколько ячейка под этой точкой считается постоянным окружением.
    /// 0 — там всё время что-то меняется, 1 — не менялось никогда.
    /// Возвращает 0, пока модель не обучена.
    double stillnessAt(const QPoint &point, const QSize &frameSize) const;

    /// То же для прямоугольника: берётся средняя неподвижность по области.
    double stillnessAt(const QRect &box, const QSize &frameSize) const;

    /// Сколько разборов учтено.
    int samples() const { return m_samples; }

    /// Обучена ли модель настолько, чтобы на неё опираться.
    bool isReady() const { return m_samples >= kMinSamples && m_agreement >= kMinAgreement; }

    /// Доля ячеек, чья изменчивость сейчас соответствует накопленной.
    ///
    /// Считается на живых кадрах. Ноль означает, что от прежней сцены не
    /// осталось ничего: камеру передвинули или помещение перестроили.
    double agreement() const { return m_agreement; }

    /// Забыть всё и начать заново. Нужно после перестановки камер.
    void reset();

    bool save(const QString &path) const;
    bool load(const QString &path);

    /// Понятное оператору описание состояния — для окна настроек.
    QString status() const;

private:
    /// Уменьшить кадр до сетки яркостей.
    static QVector<float> reduce(const QImage &frame);

    /// Средняя изменчивость ячейки: насколько она обычно отличается от себя же
    /// на прошлом разборе.
    QVector<float> m_motion = QVector<float>(kCells, 0.0f);

    /// Быстрая оценка изменчивости — по последним минутам.
    ///
    /// Нужна не для самой модели, а для сравнения с ней: если спокойные по
    /// карте ячейки вдруг зашевелились все разом, значит сцена уже не та —
    /// камеру передвинули или помещение перестроили.
    QVector<float> m_fast;

    /// Предыдущий уменьшенный кадр — не хранится в файле.
    QVector<float> m_previous;

    int m_samples = 0;
    double m_agreement = 1.0;

    /// Когда модель начали копить — для отчёта оператору.
    QString m_startedAt;
};

} // namespace core
