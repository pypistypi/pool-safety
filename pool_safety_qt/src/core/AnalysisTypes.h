//  ОДНА СТРУКТУРА НА ОДИН РАЗБОР, А НЕ РОССЫПЬ СИГНАЛОВ. Рамки, скелеты,
//  счётчик людей и уровень опасности описывают ОДИН И ТОТ ЖЕ кадр, и панель
//  обязана обновить их вместе. Порознь между ними вклинивается перерисовка, и
//  оператор видит три рамки при счётчике «2» — мелочь, из которой складывается
//  впечатление, что алгоритм считает неверно. Один раз мы на этом уже
//  обожглись.
