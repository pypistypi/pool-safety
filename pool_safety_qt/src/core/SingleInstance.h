// ---------------------------------------------------------------------------
//  Общее для main.cpp и MainWindow: как второй запуск будит первый.
//
//  ПРОБЛЕМА, КОТОРУЮ ЭТО РЕШАЕТ. Крестик сворачивает программу в значок у
//  часов — так и задумано, наблюдение не должно прерываться. Но если оператор
//  об этом забыл (или значок мелкий и незаметен) и нажал ярлык ещё раз,
//  вторая копия видела занятый мьютекс и показывала «Программа уже запущена»
//  — и на этом всё. Сообщение верное, но бесполезное: оно не говорит, где
//  искать работающее окно, и не помогает его найти. Со стороны это и
//  выглядело как «закрыл — открыть заново не получается».
//
//  Правильное поведение — то, что делает почти любая нормальная программа
//  с одним окном: вторая копия должна не ругаться, а разбудить первую и
//  закрыться сама.
// ---------------------------------------------------------------------------

#ifdef Q_OS_WIN

#include <windows.h>

namespace core::singleInstance {

/// Заголовок главного окна — по нему второй запуск находит первый.
inline const wchar_t *kMainWindowTitle = L"Наблюдение за бассейном — пост оператора";

/// Имя зарегистрированного сообщения Windows: «разверни своё окно».
///
/// RegisterWindowMessageW, а не константа вида WM_USER — у произвольного
/// WM_USER+N от других программ есть шанс совпасть и вызвать что-то чужое.
/// Зарегистрированное по имени сообщение видит только тот, кто просил именно
/// это имя.
inline UINT restoreMessage()
{
    static const UINT id = RegisterWindowMessageW(L"PoolSafety_RestoreWindow");
    return id;
}

} // namespace core::singleInstance

#endif // Q_OS_WIN
