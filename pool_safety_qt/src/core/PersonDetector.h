#pragma once

// ---------------------------------------------------------------------------
//  Распознавание человека в кадре через ONNX Runtime.
//
//  ПОДДЕРЖИВАЮТСЯ ДВА СЕМЕЙСТВА МОДЕЛЕЙ, и программа сама определяет, какое
//  перед ней, по форме выхода. Это не универсальность ради универсальности:
//  модель на объекте придётся менять (быстрее / точнее), и подмена файла не
//  должна требовать пересборки.
//
//    * YOLOX  — выход [1, 8400, 85] при входе 640 (или [1, 3549, 85] при 416).
//      Вход BGR, значения 0…255 без деления, требуется ручное разложение
//      сетки. Лицензия **Apache 2.0** — годится для коммерческого объекта.
//    * YOLOv5 — выход [1, 25200, 85]. Вход RGB, деление на 255, сетка уже
//      разложена. Лицензия Ultralytics **AGPL-3.0**, и это проблема: для
//      гостиницы она означает раскрытие исходных текстов всей системы либо
//      покупку отдельной лицензии. Поддержка оставлена ради совместимости с
//      прежней поставкой, но по умолчанию используется YOLOX.
//
//  КАДР ВПИСЫВАЕТСЯ С СОХРАНЕНИЕМ ПРОПОРЦИЙ («letterbox»), а не растягивается
//  в квадрат. Растяжение искажает фигуру: человек 16:9 становится приземистым,
//  и модель, обученная на неискажённых снимках, узнаёт его хуже. Поля
//  заливаются серым 114 — тем же значением, что при обучении.
//
//  ЛИЦА НЕ РАСПОЗНАЮТСЯ. Модель отвечает только на вопрос «здесь человек?» и
//  не различает людей между собой. Персональных данных не возникает —
//  требование заказчика и 152-ФЗ.
//
//  БИБЛИОТЕКА ЗАГРУЖАЕТСЯ ВРУЧНУЮ (см. core/OrtRuntime): сборке MinGW не нужна
//  библиотека импорта от чужого компилятора, а отсутствие DLL не роняет
//  программу, а даёт вразумительное объяснение на экране.
// ---------------------------------------------------------------------------

#include <QString>
#include <QRect>
#include <QVector>
#include <QImage>

#include <memory>

namespace core {

/// Один найденный человек.
struct Detection {
    QRect box;              ///< рамка в координатах исходного кадра
    float confidence = 0.f; ///< уверенность 0..1
};

class PersonDetector
{
public:
    /// Какая модель поиска людей используется.
    enum class Model {
        Accurate,   ///< YOLOX-s, 640 — точнее всего, ~150 мс на кадр
        Fast,       ///< YOLOX-tiny, 416 — втрое быстрее, чуть больше пропусков
        Legacy      ///< YOLOv5n — прежняя модель; лицензия AGPL-3.0
    };

    struct Config {
        QString modelPath;
        float confidenceThreshold = 0.25f;
        float nmsThreshold = 0.45f;
        /// Сколько потоков отдаём модели.
        ///
        /// ЗДЕСЬ СТОЯЛО 2 С ПОМЕТКОЙ «больше не даёт выигрыша». Замер на
        /// настоящем кадре это опроверг: YOLOX-s на двух потоках — 144 мс, на
        /// четырёх — 87 мс. На восьми снова хуже (90 мс): накладные расходы
        /// съедают выигрыш. Четыре — измеренный оптимум на восьмиядерном
        /// компьютере, и именно из-за двойки рамка отставала от человека.
        int cpuThreads = 4;
    };

    PersonDetector();
    ~PersonDetector();

    PersonDetector(const PersonDetector &) = delete;
    PersonDetector &operator=(const PersonDetector &) = delete;

    /// Загрузить модель. false — причина в lastError().
    bool load(const Config &config);

    bool isReady() const;

    /// Причина, по которой распознавание недоступно. Пустая строка — всё в
    /// порядке. Показывается оператору: молчаливо неработающий алгоритм хуже
    /// отсутствующего, потому что создаёт ложную уверенность.
    QString lastError() const;

    /// Человеческое название загруженной модели — для строки состояния.
    QString modelName() const;

    /// Найти людей в кадре. Пустой список — людей нет либо детектор не готов.
    /// Вызывать только из потока разбора: метод занимает десятки миллисекунд.
    QVector<Detection> detect(const QImage &frame);

    /// Где программа ищет модель по умолчанию.
    static QString defaultModelPath();

    /// Путь к файлу выбранной модели.
    static QString modelPath(Model model);

    /// Название модели для окна настроек.
    static QString modelTitle(Model model);

private:
    struct Impl;
    std::unique_ptr<Impl> d;
};

} // namespace core
