#pragma once

// ---------------------------------------------------------------------------
//  Где программа хранит настройки и журналы.
//
//  ДВА СПОСОБА ЗАПУСКА — ДВА РАЗНЫХ МЕСТА, и выбирать между ними должен не
//  человек, а сама программа:
//
//    * РАСПАКОВАННЫЙ АРХИВ (папка на диске, флешка, сетевой ресурс). Настройки
//      и журналы кладутся рядом с программой. Так всё хозяйство переносится
//      одной папкой, и это привычно для наладки на объекте.
//    * УСТАНОВЛЕННАЯ ПРОГРАММА (Program Files). Туда обычному пользователю
//      писать нельзя, и попытка сохранить адрес объекта молча провалилась бы.
//      Поэтому данные уходят в общий каталог ProgramData.
//
//  ПОЧЕМУ НЕ ВЫДАТЬ ПРАВА НА ЗАПИСЬ В PROGRAM FILES. Так делают, и установщик
//  это умеет, но это ослабление защиты всей системы ради одной программы:
//  папка, куда может писать любой пользователь, — известный способ подмены
//  исполняемых файлов. Windows для того и завела ProgramData.
//
//  Проверка идёт не по признаку «где лежим», а попыткой записи: она не врёт
//  ни на сетевом диске, ни на флешке с защитой, ни при необычных правах.
// ---------------------------------------------------------------------------

#include <QString>

namespace core {

namespace paths {

/// Каталог для настроек и журналов. Определяется один раз при первом
/// обращении и дальше не меняется.
QString dataDir();

/// Файл настроек программы.
QString settingsFile();

/// Файл сведений об объекте.
QString siteFile();

/// Папка журналов.
QString logsDir();

/// true — данные лежат рядом с программой (переносной запуск).
bool isPortable();

} // namespace paths

} // namespace core
