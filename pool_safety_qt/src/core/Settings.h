#pragma once

// ---------------------------------------------------------------------------
//  Настройки программы, которые администратор объекта меняет сам.
//
//  ПОЧЕМУ ОНИ ВЫНЕСЕНЫ ИЗ КОДА. Громкость сирены, время терпения перед
//  тревогой, чувствительность поиска людей — всё это придётся подгонять на
//  месте: под высоту камеры, под шум в зале, под привычки смены. Если ради
//  каждой правки нужен разработчик, настройка не произойдёт никогда, и система
//  останется работать с числами, подобранными в чужой комнате.
//
//  Файл лежит рядом с программой в `config/settings.json` и правится либо из
//  окна «Настройки», либо блокнотом.
//
//  СВЕДЕНИЯ ОБ ОБЪЕКТЕ (адрес, телефоны) живут отдельно, в `config/site.json`:
//  их правят другие люди и по другому поводу — см. core/SiteInfo.h.
// ---------------------------------------------------------------------------

#include "core/PersonDetector.h"
#include "core/SituationRules.h"

#include <QString>
#include <QVector>

namespace core {

struct Settings {
    // --- общий рубильник реакций -------------------------------------------
    //
    // Выключает ВСЕ автоматические отклики: звуки, всплывающие строки,
    // автоматическую тревогу. Остаётся показ видео, счётчик людей, журнал и
    // тревога вручную.
    //
    // ЗАЧЕМ ЭТО НУЖНО. На новом объекте, пока пороги не подогнаны под сцену,
    // система будет шуметь. Оператор, которому нечем её унять, просто
    // выключит программу целиком — и объект останется вовсе без наблюдения.
    // Пусть лучше выключит отклики осознанно и на время настройки.
    bool reactionsEnabled = true;

    /// Откликаться ли на появление людей (звук и строка). Сам счётчик и
    /// зелёная подсветка панели остаются: это не отклик, а показания.
    bool presenceReaction = true;

    // --- звук --------------------------------------------------------------
    bool soundEnabled = true;

    /// Громкость тревоги, 0..1. По умолчанию высокая: сигнал обязан
    /// перекрыть шум зала и разговоры.
    double alarmVolume = 0.9;

    /// Громкость спокойного уведомления о появлении людей.
    double presenceVolume = 0.22;

    /// Как часто повторяется сирена, пока тревога не принята, секунд.
    int alarmRepeatSeconds = 3;

    /// Через сколько секунд без реакции сигнал усиливается: сирена звучит
    /// чаще и громче. Ноль — не усиливать.
    int escalateAfterSeconds = 20;

    // --- поведение окна ----------------------------------------------------
    /// При каком уровне выводить окно поверх остальных:
    /// 0 — никогда, 1 — уже при «внимании», 2 — только при тревоге.
    ///
    /// ЗАЧЕМ ВЫБОР. Программа работает круглосуточно, и на том же компьютере
    /// оператор ведёт учёт, смотрит записи, отвечает на почту. Окно, лезущее
    /// вперёд по каждому поводу, он свернёт и забудет — а окно, не лезущее
    /// никогда, бесполезно.
    int popupLevel = 2;

    /// Сворачиваться в значок у часов вместо закрытия.
    bool minimizeToTray = true;

    /// Разворачивать окно и выводить его поверх остальных.
    bool raiseWindowOnAlarm = true;

    /// Мигать значком в панели задач, пока тревога не принята.
    bool flashTaskbarOnAlarm = true;

    /// Мигать рамкой окна. Отключается для тех, кому мигание мешает.
    bool blinkOnAlarm = true;

    // --- присутствие -------------------------------------------------------
    /// Подавать звук при появлении людей в зоне. Это НЕ тревога.
    bool presenceSound = true;

    // --- распознавание -----------------------------------------------------
    /// Миллисекунд между разборами одной панели.
    /// Версия настроек — по ней делается разовый перевод старых файлов.
    ///
    /// ЗАЧЕМ ОНА НУЖНА. Настройки, однажды сохранённые, перекрывают умолчания
    /// программы навсегда. Значит улучшение, живущее в умолчании, до уже
    /// работающего объекта не доедет никогда: там в файле останется прежнее
    /// значение, и обновление ничего не изменит.
    static constexpr int kCurrentVersion = 2;
    int version = kCurrentVersion;

    /// Как часто разбирается кадр.
    ///
    /// ВОТ ГЛАВНАЯ ПРИЧИНА, ПО КОТОРОЙ РАМКА ОТСТАВАЛА. Здесь стояло 400 мс,
    /// то есть два с половиной разбора в секунду при видео в тридцать кадров.
    /// Сам разбор занимал вдвое меньше — остальное время поток простаивал.
    /// Со 120 мс и четырьмя потоками моделей рамка обновляется вчетверо чаще.
    int detectIntervalMs = 120;

    /// Учить ли карту постоянного окружения.
    ///
    /// ЧТО ЭТО ДАЁТ. Программа копит, какие места кадра никогда не меняются:
    /// стена, дно, дверной проём. Слабый отклик модели в таком месте — почти
    /// наверняка не человек, а узор плитки или тень, и к нему стоит отнестись
    /// строже. Уверенный отклик проходит всегда: человек может стоять
    /// неподвижно, и в мёртвом углу кадра он тем более важен.
    ///
    /// КОГДА ВКЛЮЧАТЬ. Когда камеры стоят неподвижно и обстановка меняется
    /// мало. Перевесили камеру или перестроили помещение — обучение надо
    /// начать заново; программа заметит расхождение и сама перестанет на него
    /// опираться, но лучше не доводить.
    bool selfLearning = true;

    /// Порог уверенности поиска людей.
    ///
    /// Замерено на записи с идущими людьми (120 кадров, YOLOX-s): при 0,25
    /// в кадре находится в среднем 5,7 человека и провалы счёта случаются в
    /// 35 % кадров; при 0,40 — 5,3 человека и 44 % провалов. Пропущенный
    /// человек здесь дороже лишней рамки, поэтому порог низкий.
    double searchConfidence = 0.25;

    /// Считать позу и опасные положения.
    bool poseEnabled = true;

    /// Какая модель ищет людей.
    PersonDetector::Model detectorModel = PersonDetector::Model::Accurate;

    // --- связь с телефонами ------------------------------------------------
    /// Раздавать события телефонам в локальной сети.
    bool serverEnabled = true;

    /// Порт, на котором ждут телефоны.
    int serverPort = 8765;

    /// Поднимать тревогу автоматически по найденному опасному положению.
    /// Выключение оставляет только подсветку панели и запись в журнал —
    /// режим для периода настройки на новом объекте.
    bool autoAlarm = true;

    /// Смотрит ли панель на воду — по одному признаку на каждую из четырёх.
    ///
    /// ПОЧЕМУ ЭТО НЕ УГАДЫВАЕТСЯ. Программа определяет «человек в воде» по
    /// тому, что не видно ног. На бассейне это работает, в комнате — нет:
    /// ноги закрывает стол, лежак, другой человек. Проверено на веб-камере —
    /// сидящий за столом взрослый получал тревогу «ребёнок в воде без
    /// взрослого». Поэтому воду отмечает оператор, а до отметки водные
    /// правила молчат.
    QVector<bool> panelHasWater = {false, false, false, false};

    Thresholds thresholds;

    static Settings load(const QString &path);
    bool save(const QString &path) const;
    static QString defaultPath();
};

} // namespace core
