// ---------------------------------------------------------------------------
//  Биомеханика позы: измеримые величины вместо «нейросеть решила».
//
//  ЗАЧЕМ ЭТОТ СЛОЙ. Можно было бы подать картинку ещё одной нейросети и ждать
//  ответа «тонет / не тонет». Но такой ответ нечем проверить и нечем
//  объяснить оператору, а главное — не на чем обучить: записей настоящих
//  утоплений нет ни у кого.
//
//  Поэтому между позой и решением стоит слой обычных измерений, как в
//  безмаркерном анализе движения: углы в суставах, наклон звеньев тела,
//  положение центра масс. Каждая величина имеет физический смысл, её можно
//  показать на экране, проверить на постановочной съёмке и объяснить словами:
//  «тревога поднята потому, что туловище вертикально, голова у линии воды, а
//  продвижения нет уже двенадцать секунд».
//
//  Все углы — в градусах. Все расстояния — В ДОЛЯХ ДЛИНЫ ТУЛОВИЩА, а не в
//  точках экрана: человек у дальнего бортика вдвое мельче, чем у ближнего, а
//  сгибается одинаково.
// ---------------------------------------------------------------------------

#include "core/Skeleton.h"

#include <QPointF>

#include <optional>

namespace core {

/// Мгновенные признаки одной позы. Пустое значение — измерить не удалось,
/// и притворяться, что удалось, нельзя.
struct PoseFeatures {
    // --- положение тела ---------------------------------------------------
    std::optional<double> torsoTilt;       ///< наклон туловища от вертикали, °
    std::optional<double> headAboveHips;   ///< насколько голова выше бёдер, в длинах туловища
    std::optional<double> torsoLength;     ///< длина туловища, точек экрана — мера масштаба
    std::optional<double> bodyHeight;      ///< высота видимой фигуры, точек экрана

    /// Ширина плеч, точек экрана.
    ///
    /// Нужна, чтобы отличить нормально видимую фигуру от снятой в сильном
    /// ракурсе. У человека, сидящего вплотную к камере, туловище видно
    /// укороченным, а плечи остаются широкими — и все измерения, где длина
    /// туловища стоит в знаменателе, разлетаются.
    std::optional<double> shoulderWidth;

    // --- углы в суставах --------------------------------------------------
    std::optional<double> kneeLeft;
    std::optional<double> kneeRight;
    std::optional<double> elbowLeft;
    std::optional<double> elbowRight;
    std::optional<double> hipLeft;
    std::optional<double> hipRight;

    // --- что вообще видно -------------------------------------------------
    bool headVisible = false;
    double lowerBodyRatio = 0.0;   ///< доля видимых точек ниже пояса, 0..1
    double quality = 0.0;          ///< средняя уверенность по значимым точкам

    // --- руки -------------------------------------------------------------
    int wristsAboveShoulders = 0;
    std::optional<double> wristSpread;

    // --- центр и опора ----------------------------------------------------
    std::optional<QPointF> center;      ///< центр масс (приближённо), точки экрана
    std::optional<double> supportWidth; ///< ширина опоры между стопами, в долях туловища

    // --- пропорции --------------------------------------------------------
    std::optional<double> headToTorso;  ///< размер головы к длине туловища

    /// Хватает ли измерений, чтобы делать выводы.
    ///
    /// Без оси туловища не считается ничего: ни наклон, ни доли длины. Молча
    /// выдавать выводы по обрывкам скелета опаснее, чем признать, что человек
    /// виден плохо.
    bool isUsable() const { return torsoTilt.has_value() && torsoLength.has_value(); }
};

PoseFeatures extractFeatures(const Pose &pose);

/// Лежит ли человек. Порог 55°, а не 90°: лежащий на боку у бортика редко
/// вытянут ровно по горизонтали, а опасность та же.
bool isHorizontal(const PoseFeatures &features, double threshold = 55.0);

bool isUpright(const PoseFeatures &features, double threshold = 30.0);

/// Похоже, что нижняя часть тела скрыта — обычно водой.
///
/// Способ грубый: ноги может закрывать лежак или другой человек. Поэтому
/// вывод называется «похоже», а не «в воде», и сам по себе тревогу не
/// поднимает — только вместе с другими признаками.
bool looksSubmerged(const PoseFeatures &features);

} // namespace core
