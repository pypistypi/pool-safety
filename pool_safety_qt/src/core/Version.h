#pragma once

// ---------------------------------------------------------------------------
//  Версия программы. Одна на всех.
//
//  ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ РАДИ ОДНОЙ СТРОКИ. Потому что версия жила в четырёх
//  местах сразу — в точке входа, в сервере событий, в скрипте сборки и в
//  установщике — и к выпуску 1.1.0 они разошлись: программа называла себя
//  0.4.0, установщик собирался как 1.0.0, а телефону сервер представлялся
//  как 1.1.0. Ни одна из этих цифр не была верной целиком.
//
//  Теперь строка одна. Скрипт сборки читает её отсюда же и передаёт
//  установщику, так что разойтись им больше негде.
//
//  ПЯТОЕ МЕСТО НАШЛОСЬ ПОЗЖЕ: ресурс Windows (deploy/PoolSafety.rc) хранил
//  FILEVERSION отдельной строкой, и после этого самого рефакторинга свойства
//  файла в проводнике продолжали показывать «1.0.0», пока код внутри уже
//  отвечал версией 1.3.0 — расхождение обнаружилось только при разборе
//  жалобы на совсем другую вещь и увело по ложному следу. Поэтому ниже не
//  просто строка для C++, а простые макросы: компилятор ресурсов Windows
//  (windres) понимает только их — ни пространств имён, ни constexpr он не
//  разбирает. RC_INVOKED определяется им самим при разборе .rc-файла, и это
//  единственное, что позволяет .rc подключить этот же заголовок напрямую, а
//  не завести шестое место со своим текстом версии.
// ---------------------------------------------------------------------------

#define POOL_SAFETY_VERSION_MAJOR 1
#define POOL_SAFETY_VERSION_MINOR 6
#define POOL_SAFETY_VERSION_PATCH 0
#define POOL_SAFETY_VERSION_STR   "1.6.0"

#ifndef RC_INVOKED

namespace core {

/// Версия программы в виде «главная.дополнительная.правка».
inline constexpr const char *kAppVersion = POOL_SAFETY_VERSION_STR;

} // namespace core

#endif // RC_INVOKED
