#pragma once

// ---------------------------------------------------------------------------
//  Сведения об объекте — то, что оператор обязан продиктовать в трубку.
//
//  ЗАЧЕМ ЭТО ВЫНЕСЕНО В ОТДЕЛЬНЫЙ ФАЙЛ НАСТРОЕК. В момент, когда человек
//  тонет, оператор не должен вспоминать адрес, номер корпуса и как объяснить
//  скорой, куда заезжать. Всё это заготавливается заранее, один раз, в
//  спокойной обстановке — и в тревоге просто показывается на экране крупными
//  буквами.
//
//  ПРОГРАММА НЕ ПРИДУМЫВАЕТ АДРЕС. Если он не заполнен, она об этом прямо
//  говорит и требует заполнить. Выдуманный адрес хуже отсутствующего: по нему
//  уедет скорая.
//
//  Настройки лежат рядом с программой в `config/site.json` и правятся обычным
//  блокнотом — менять их будет администратор объекта, а не разработчик.
// ---------------------------------------------------------------------------

#include <QString>
#include <QVector>

namespace core {

/// Телефон экстренной службы или ответственного лица.
struct EmergencyContact {
    QString title;   ///< кому звоним: «Единая служба спасения», «Старший смены»
    QString phone;
    QString note;    ///< когда именно звонить
};

struct SiteInfo {
    QString objectName;    ///< «Гостиничный комплекс …, крытый бассейн»
    QString address;       ///< полный адрес для скорой
    QString landmark;      ///< ориентир: как найти въезд
    QString entrance;      ///< куда идти внутри: корпус, этаж, вход
    QString responsible;   ///< кто отвечает за объект
    QVector<EmergencyContact> contacts;

    /// Адрес заполнен и годится для вызова помощи.
    bool isAddressReady() const;

    /// Прочитать из файла. Если файла нет, он создаётся с заготовкой, которую
    /// администратору останется дополнить.
    static SiteInfo load(const QString &path);

    /// Заготовка: телефоны экстренных служб настоящие, а всё, что относится к
    /// конкретному объекту, помечено как незаполненное.
    static SiteInfo defaults();

    bool save(const QString &path) const;

    /// Где программа ищет файл настроек.
    static QString defaultPath();
};

} // namespace core
