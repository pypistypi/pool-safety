#pragma once

// ---------------------------------------------------------------------------
//  Сопровождение людей и накопление истории движений.
//
//  ЗАЧЕМ ИСТОРИЯ. Один кадр не отличает игру от беды. Человек, застывший в
//  воде вертикально, на снимке выглядит одинаково и когда отдыхает, и когда
//  тонет. Разница — в том, что происходит дальше:
//
//      пловец     — продвигается вперёд;
//      играющий   — то ныряет, то выныривает, движения размашистые;
//      отдыхающий — стоит, но голова уверенно над водой;
//      тонущий    — не продвигается никуда, голова у самой воды, движения
//                   затухают.
//
//  Всё это — величины, измеримые только на отрезке времени в несколько
//  секунд. Поэтому каждому человеку заводится дорожка, и по ней считаются
//  признаки: сколько он неподвижен, насколько сместился, как менялся наклон.
//
//  СОПОСТАВЛЕНИЕ ПО ПОЛОЖЕНИЮ, А НЕ ПО ВНЕШНОСТИ. Это сознательно: сравнение
//  по внешности означало бы биометрию, которая в этой системе запрещена.
//  Побочный эффект — при пересечении двух людей дорожки могут поменяться
//  местами; для задачи «есть ли опасность» это не страшно, потому что тревога
//  поднимается по месту, а не по личности.
//
//  ПОЧЕМУ ПРОСТОГО ПЕРЕСЕЧЕНИЯ РАМОК НЕ ХВАТАЕТ — И ЭТО БЫЛА САМАЯ ДОРОГАЯ
//  ОШИБКА СИСТЕМЫ. Разбор идёт несколько раз в секунду, а не тридцать: за
//  четыре десятых секунды идущий человек смещается на полкорпуса, и его новая
//  рамка почти не перекрывается с прежней. Дорожка обрывается, человек
//  получает новый номер, накопленное время обнуляется.
//
//  Замерено на записи с идущими людьми (100 разборов, в среднем 6 человек в
//  кадре):
//
//      только пересечение рамок 0,25   → 204 дорожки, живёт  1,2 с
//      предсказание + порог 0,15       →  71 дорожка,  живёт  3,5 с
//      то же плюс близость центров     →  22 дорожки,  живёт 11,3 с
//
//  При жизни дорожки в 1,2 секунды пороги «лежит 10 секунд» и «завис в воде 9
//  секунд» недостижимы В ПРИНЦИПЕ: система молчала бы ровно там, где обязана
//  кричать. Поэтому здесь три ступени сопоставления — предсказание положения
//  по скорости, пересечение предсказанной рамки и, если не сошлось, близость
//  центров при похожем размере.
// ---------------------------------------------------------------------------

#include "core/Biomechanics.h"
#include "core/Skeleton.h"

#include <QVector>
#include <QHash>

#include <deque>
#include <optional>

namespace core {

/// Один замер по человеку.
struct Sample {
    double timestamp = 0.0;
    PoseFeatures features;
    Pose pose;
};

/// Признаки, посчитанные по отрезку времени.
struct WindowMetrics {
    double span = 0.0;                      ///< длина отрезка, секунд
    std::optional<double> motion;           ///< средняя скорость точек, длин туловища в секунду
    std::optional<double> displacement;     ///< смещение центра за отрезок, в длинах туловища
    double stillSeconds = 0.0;              ///< сколько секунд подряд человек неподвижен
    double horizontalSeconds = 0.0;         ///< сколько секунд подряд лежит
    double uprightSubmergedSeconds = 0.0;   ///< вертикально и без видимых ног
    double tiltChange = 0.0;                ///< наибольшее изменение наклона за секунду, °
    std::optional<double> sway;             ///< боковые колебания пути, в долях туловища
    double headVisibleRatio = 1.0;          ///< доля времени с видимой головой
    std::optional<double> armActivity;      ///< активность кистей, длин туловища в секунду
    double submergedRatio = 0.0;            ///< доля времени без видимых ног
};

/// Дорожка одного человека.
class Track
{
public:
    explicit Track(int id = 0, double created = 0.0)
        : m_id(id), m_created(created), m_lastSeen(created) {}

    int id() const { return m_id; }
    double lastSeen() const { return m_lastSeen; }
    double age() const { return m_lastSeen - m_created; }
    bool isEmpty() const { return m_samples.empty(); }

    const Sample *latest() const { return m_samples.empty() ? nullptr : &m_samples.back(); }

    void add(double timestamp, const Pose &pose);

    /// Посчитать признаки движения.
    ///
    /// ОКНО И ИСТОРИЯ — РАЗНЫЕ ВЕЩИ, и путать их нельзя.
    ///
    /// По ОКНУ (последние `window` секунд) считается всё, что описывает
    /// движение прямо сейчас: скорость, продвижение, виляние. Брать их за
    /// полминуты бессмысленно — человек успел сделать десяток разных дел.
    ///
    /// По ВСЕЙ ИСТОРИИ считается длительность состояний: сколько человек уже
    /// лежит, сколько неподвижен, был ли резкий переход в горизонталь.
    /// Считать их внутри окна — ошибка, делающая систему слепой: порог
    /// «десять секунд неподвижности» внутри шестисекундного окна недостижим в
    /// принципе, а падение, случившееся восемь секунд назад, просто выпадает
    /// из окна вместе со всей причиной тревоги.
    WindowMetrics metrics(double window = 6.0) const;

    /// Сколько секунд подряд человек практически не двигается.
    ///
    /// Порог 0,04 длины туловища в секунду — примерно сантиметр в секунду для
    /// взрослого. Живой человек, даже стоящий, столько набирает дыханием и
    /// покачиванием; кто лежит без сознания — нет.
    double stillnessSeconds() const { return since(m_stillSince); }

    /// Сколько секунд подряд человек лежит.
    double horizontalSeconds() const { return since(m_horizontalSince); }

    /// Сколько секунд подряд человек вертикален и без видимых ног.
    double uprightSubmergedSeconds() const { return since(m_submergedSince); }

    /// Насколько резким был переход в горизонталь, которым объясняется
    /// текущая неподвижность лёжа — °/с. Ноль, если человек лёг медленно
    /// (загорающий садится на лежак плавно) или сейчас не лежит вовсе.
    ///
    /// УТОЧНЯЕТСЯ ПЕРВЫЕ kFallSettleSeconds ПОСЛЕ ПЕРЕХОДА, а дальше
    /// ЗАМОРАЖИВАЕТСЯ и не пересчитывается, пока человек не встанет. Раньше
    /// правило падения (см. fall() в
    /// SituationRules.cpp) сверялось с этим значением заново на каждом
    /// разборе позы — а оно считалось по хранимой истории, которая не длиннее
    /// kHistorySeconds (15 с). Через пятнадцать секунд после самого падения
    /// свидетельство резкого поворота уходило из истории, tiltChange падал до
    /// нуля, и правило гасло — хотя человек так и лежал без сознания. Именно
    /// так тревога о настоящем падении однажды не прозвучала.
    double fallTiltRate() const { return m_fallTiltRate; }

    /// Где рамка человека окажется к моменту `timestamp`, если он продолжит
    /// двигаться как двигался. Именно с ней сравниваются новые находки.
    QRect predictedBox(double timestamp) const;

    /// Порог неподвижности: длин туловища в секунду.
    static constexpr double kStillThreshold = 0.04;

    /// Сколько секунд после перехода в горизонталь ещё уточняется резкость
    /// падения (см. fallTiltRate()). Сглаживающая медиана не может распознать
    /// устойчивый скачок наклона в тот же кадр, где он случился, — ей нужно
    /// два-три замера ПОСЛЕ перехода, иначе она примет его за одиночный сбой
    /// скелета и отбросит (ровно то, для чего она и поставлена). 1,5 секунды
    /// при разборе поз трижды в секунду — это четыре-пять замеров, с запасом.
    static constexpr double kFallSettleSeconds = 1.5;

private:
    double since(double moment) const { return qMax(0.0, m_lastSeen - moment); }
    void updateDurations(double timestamp, const Sample &previous,
                         const PoseFeatures &features, const Pose &pose);

    int m_id = 0;
    double m_created = 0.0;
    double m_lastSeen = 0.0;
    QPointF m_velocity;          ///< сглаженная скорость центра, точек в секунду
    std::deque<Sample> m_samples;

    // --- длительности состояний ------------------------------------------
    //
    // ПОЧЕМУ ОНИ СЧИТАЮТСЯ НАКОПИТЕЛЬНО, А НЕ ПО ХРАНИМОЙ ИСТОРИИ. История
    // ограничена пятнадцатью секундами: держать в памяти позы каждого
    // человека за несколько минут — это мегабайты на ровном месте. Но пороги
    // правил бывают куда длиннее: «лежит на суше три минуты», «взрослый
    // неподвижен двадцать секунд». Считай их по истории — они оказались бы
    // недостижимы в принципе, и система молчала бы, выглядя исправной.
    //
    // Поэтому здесь хранится не история состояния, а МОМЕНТ ЕГО НАЧАЛА:
    // условие держится — момент не трогаем, нарушилось — сдвигаем на сейчас.
    // Память постоянна, а длительность не ограничена ничем.
    double m_stillSince = 0.0;
    double m_horizontalSince = 0.0;
    double m_submergedSince = 0.0;
    double m_fallTiltRate = 0.0;
};

class PersonTracker
{
public:
    /// Сколько секунд истории хранить. Пятнадцати хватает: дольше человек
    /// либо уже спасён, либо тревога давно поднята.
    static constexpr double kHistorySeconds = 15.0;

    /// Сколько секунд дорожка живёт без обновлений. Две секунды —
    /// компромисс: человек может нырнуть и пропасть из виду, но бесконечно
    /// хранить дорожки нельзя, иначе они накопятся и начнут путаться.
    static constexpr double kHoldSeconds = 2.0;

    /// Насколько ПРЕДСКАЗАННАЯ рамка должна совпасть с новой. Порог ниже
    /// прежнего 0,25: предсказание уже учло смещение, и требовать от него
    /// четверти перекрытия значит снова рвать дорожки.
    static constexpr double kIouThreshold = 0.15;

    /// Запасное сопоставление: центр новой рамки ближе этой доли высоты
    /// предсказанной, а размеры отличаются не в разы. Спасает, когда человек
    /// прошёл больше собственной ширины между разборами.
    static constexpr double kCentreDistance = 0.8;
    static constexpr double kSizeRatioLow = 0.6;
    static constexpr double kSizeRatioHigh = 1.7;

    /// Обновить дорожки позами текущего кадра. Возвращает номера дорожек,
    /// обновлённых этим кадром.
    QVector<int> update(const QVector<Pose> &poses, double timestamp);

    /// Все живые дорожки.
    QVector<const Track *> tracks() const;

    const Track *track(int id) const;

    void reset();

private:
    QHash<int, Track> m_tracks;
    int m_nextId = 1;
};

} // namespace core
